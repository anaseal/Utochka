export type BeadType = 'NODE' | 'SPAN';

export interface Bead {
  id: string;
  x: number;
  y: number;
  type: BeadType;
  logicalIndex: { row: number; col: number };
}

export interface GridConfig {
  width: number;
  height: number;
  spacing: number;
  topSpan: number;
  bottomSpan: number;
}

export interface BottomEdgeDecor {
  enabled: boolean;
}

// Регулирует, заходят ли нечётные (сдвинутые) ряды на полшага левее/правее
// чётных (c=-1 / c=width-1) — полный ромб у самого края слева/справа
// независимо друг от друга, вместо всегда включённого расширения (см. spec.md).
export interface EdgeExtension {
  left: boolean;
  right: boolean;
}

// Сужение концов полотна (верхнего и/или нижнего). Срезает целое число
// колонок с каждой стороны каждого узлового ряда (getTaperColumnCut в
// src/utils/taper.ts), а не сдвигает границы колонок статично и не режет по
// пиксельной координате — число срезаемых колонок посчитано напрямую для
// каждого узлового ряда и монотонно убывает к краю зоны скоса, поэтому кромка
// не даёт «зубцов». SPAN-бисерины на диагоналях решаются по топологии (оба
// узла-конца пролёта должны уцелеть), а не по координате — без висячих бусин.
//   rows  — стартовый срез (в колонках) у самого края этой стороны; убывает
//           на пол-колонки за каждый узловой ряд по мере удаления от края.
//           rows=0 — эта сторона выключена целиком, вне зависимости от depth.
//   depth — ОБЩИЙ для top и bottom (не per-side): в половинках колонки, ПОЛ
//           ширины, к которому убывающий срез любой активной стороны сходится
//           и на котором держится сколь угодно далеко от своего края — то есть
//           это минимальная ширина всего полотна, а не локальная особенность
//           одного края. depth=0 не то же самое, что обе стороны выключены:
//           кромки всё равно срезаются по rows, просто далеко от них
//           полотно возвращается к полной ширине.
// (см. spec.md, «Сужение концов (Taper)»).
export interface TaperSide {
  rows: number;
}

export interface Taper {
  top: TaperSide;
  bottom: TaperSide;
  depth: number;
}
