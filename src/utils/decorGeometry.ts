import { BEAD_THEME } from '../config/theme';

// Шаг между декор-рядами (полоса между узловыми рядами, generator.ts, и
// индивидуальный хвост decorTail.ts) — общая формула для обоих, чтобы бисерины
// выглядели одинаково независимо от того, кто их разместил. Бисерины декора
// стоят строго друг под другом по одному X (в отличие от обычных пролётов
// сетки, где соседние ряды разнесены ещё и по X на stepX/2), поэтому нижняя
// граница шага не может быть меньше минимального физического пролёта между
// бисеринами — иначе соседние ряды/бисерины хвоста наложатся друг на друга
// при низком spacing.
export const getDecorRowStep = (spacing: number): number =>
  Math.max(
    spacing * BEAD_THEME.gridDefaults.verticalCompression,
    BEAD_THEME.sizes.spanRadius * 2 + 2,
  );
