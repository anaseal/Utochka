import { DrawingTool } from '../hooks/useDrawing';

// Инструменты, работающие протяжкой: нажатие открывает мазок, движение по
// бисеринам красит, отпускание закрывает мазок в истории (см. useDrawing).
// Остальные — точечные: заливка и штамп срабатывают по одному клику, а нитка
// и цепочка-подвеска набирают точки отдельными кликами. Для них
// startDrawing/stopDrawing звать нельзя — пустой мазок засорял бы историю
// Undo, а уход курсора с холста закрывал бы чужой.
export const isStrokeTool = (tool: DrawingTool): boolean =>
  tool === 'pencil' || tool === 'eraser';
